static void grow_line_segment(int32_t *pos_point_ptr, int32_t *length_ptr) {
  if (*pos_point_ptr > INT32_MIN) {
    *pos_point_ptr -= 1;
    if (*length_ptr < INT32_MAX - 1) {
      *length_ptr += 2;
    } else if (*length_ptr < INT32_MAX) {
      *length_ptr += 1;
    }
  } else {
    if (*length_ptr < INT32_MAX) {
      *length_ptr += 1;
    }
  }
}

static bool check_screen_touch(struct output_geometry scr1,
  struct output_geometry scr2) {
  /*
   * We check for both touching and overlapping screens. Screens are
   * overlapping if their defining horizontal and vertical line segments both
   * overlap. To detect touching screens, we can simply grow the size of one of
   * the screens by one pixel in every direction (i.e., subtract one from both
   * the X and Y position coordinates and then add two to the width and
   * height). Then any form of screen touching will be seen as an overlap,
   * including touching at the corners.
   */

  if (scr1.width < 0 || scr1.height < 0 || scr2.width < 0 || scr2.height < 0) {
    return false;
  }

  grow_line_segment(&scr1.x, &scr1.width);
  grow_line_segment(&scr1.y, &scr1.height);

  if (scr1.x < (scr2.x + scr2.width)
    && scr2.x < (scr1.x + scr1.width)
    && scr1.y < (scr2.y + scr2.height)
    && scr2.y < (scr1.y + scr1.height)) {
    return true;
  }

  return false;
}

static struct screen_local_coord abs_coord_to_screen_local_coord(int32_t x,
  int32_t y) {
  struct screen_local_coord out_data = EMPTY_SCREEN_LOCAL_COORD;
  int32_t cur_geom_x = 0;
  int32_t cur_geom_y = 0;
  int32_t cur_geom_width = 0;
  int32_t cur_geom_height = 0;

  for (int32_t i = 0; i < MAX_SCREEN_COUNT; i++) {
    if (!state.output_geometries[i]) {
      continue;
    }

    cur_geom_x = state.output_geometries[i]->x;
    cur_geom_y = state.output_geometries[i]->y;
    cur_geom_width = state.output_geometries[i]->width;
    cur_geom_height = state.output_geometries[i]->height;
    if (cur_geom_width < 0 || cur_geom_height < 0) {
      continue;
    }

    if (!(x >= cur_geom_x)) {
      continue;
    }
    if (!(y >= cur_geom_y)) {
      continue;
    }
    if (!(x < cur_geom_x + cur_geom_width)) {
      continue;
    }
    if (!(y < cur_geom_y + cur_geom_height)) {
      continue;
    }
    out_data.output_idx = i;
    out_data.x = x - cur_geom_x;
    out_data.y = y - cur_geom_y;
    break;
  }

  return out_data;
}

static struct coord screen_local_coord_to_abs_coord(int32_t x, int32_t y,
  int32_t output_idx, bool *out_is_valid) {
  int32_t cur_geom_x = 0;
  int32_t cur_geom_y = 0;
  int32_t cur_geom_width = 0;
  int32_t cur_geom_height = 0;
  struct coord out_val = { .x = 0, .y = 0 };

  *out_is_valid = false;

  assert(output_idx >= 0);
  assert(output_idx < MAX_SCREEN_COUNT);
  if (x < 0 || y < 0) {
    return out_val;
  }

  if (!state.output_geometries[output_idx]) {
    return out_val;
  }
  cur_geom_x = state.output_geometries[output_idx]->x;
  cur_geom_y = state.output_geometries[output_idx]->y;
  cur_geom_width = state.output_geometries[output_idx]->width;
  cur_geom_height = state.output_geometries[output_idx]->height;
  if (cur_geom_width < 0 || cur_geom_height < 0) {
    return out_val;
  }
  if (x >= cur_geom_width || y >= cur_geom_height) {
    return out_val;
  }

  out_val.x = cur_geom_x + x;
  out_val.y = cur_geom_y + y;
  *out_is_valid = true;
  return out_val;
}

struct coord traverse_line(struct coord start, struct coord end,
  int32_t pos, bool *out_success) {
  /*
   * Based on Zingl Alois' implementation of Bresenham's algorithm for line
   * drawing (https://zingl.github.io/bresenham.c function plotLine()),
   * modified to return a specific point from a line rather than drawing the
   * whole line to a canvas.
   */
  static struct coord last_start = { 0 };
  static struct coord last_end = { 0 };
  static struct coord work_coord = { 0 };
  static struct coord err_adj = { 0 };
  static struct coord direct_adj = { 0 };
  static int32_t err_val = 0;
  static int32_t err_2x_val = 0;
  static int32_t last_pos = 0;
  static int32_t max_pos = 0;
  static int32_t max_x = 0;
  static int32_t max_y = 0;
  int32_t i = 0;

  assert(pos >= 0);
  *out_success = true;

  /*
   * We could include code to traverse the line backwards when needed, but
   * kloak doesn't ever need to do that so there's no point.
   */
  if (last_start.x != start.x || last_start.y != start.y
    || last_end.x != end.x || last_end.y != end.y || pos < last_pos) {
    work_coord = start;
    err_adj.x = end.x - start.x;
    assert(err_adj.x != INT32_MIN);
    err_adj.x = abs(err_adj.x);
    err_adj.y = end.y - start.y;
    assert(err_adj.y != INT32_MIN);
    err_adj.y = -abs(err_adj.y);
    direct_adj.x = start.x < end.x ? 1 : -1;
    direct_adj.y = start.y < end.y ? 1 : -1;
    err_val = err_adj.x + err_adj.y;
    err_2x_val = 0;
    last_start = start;
    last_end = end;
    last_pos = 0;
    max_x = end.x - start.x;
    assert(max_x != INT32_MIN);
    max_x = abs(max_x);
    max_y = end.y - start.y;
    assert(max_y != INT32_MIN);
    max_y = abs(max_y);
    max_pos = MAX(max_x, max_y);
  }

  if (pos > max_pos) {
    *out_success = false;
    return work_coord;
  }
  if (pos == last_pos) {
    return work_coord;
  }

  for (i = 0; i < pos - last_pos; i++) {
    err_2x_val = err_val * 2;
    if (err_2x_val >= err_adj.y) {
      if (work_coord.x == end.x) {
        break;
      }
      err_val += err_adj.y;
      work_coord.x += direct_adj.x;
    }
    if (err_2x_val <= err_adj.x) {
      if (work_coord.y == end.y) {
        break;
      }
      err_val += err_adj.x;
      work_coord.y += direct_adj.y;
    }
  }
  last_pos = pos;
  return work_coord;
}

static void draw_block(uint32_t *pixbuf, int32_t offset, int32_t x, int32_t y,
  int32_t layer_width, int32_t layer_height, int32_t rad, bool crosshair) {
  int32_t start_x = 0;
  int32_t start_y = 0;
  int32_t end_x = 0;
  int32_t end_y = 0;
  int32_t work_x = 0;
  int32_t work_y = 0;

  assert(should_draw_cursor);

  start_x = x - rad;
  if (start_x < 0) start_x = 0;
  start_y = y - rad;
  if (start_y < 0) start_y = 0;
  end_x = x + rad;
  if (end_x >= layer_width) end_x = layer_width - 1;
  end_y = y + rad;
  if (end_y >= layer_height) end_y = layer_height - 1;

  for (work_y = start_y; work_y <= end_y; work_y++) {
    for (work_x = start_x; work_x <= end_x; work_x++) {
      if (crosshair && work_x == x) {
        pixbuf[offset + (work_y * layer_width + work_x)] = cursor_color;
      } else if (crosshair && work_y == y) {
        pixbuf[offset + (work_y * layer_width + work_x)] = cursor_color;
      } else {
        pixbuf[offset + (work_y * layer_width + work_x)] = 0x00000000;
      }
    }
  }
}

static int32_t get_ticks_from_scroll_accum(double *accum_ptr) {
  double scroll_ticks_d = 0.0;
  int32_t scroll_ticks = 0;

  if (fpclassify(*accum_ptr) != FP_ZERO) {
    assert(isfinite(*accum_ptr));
    scroll_ticks_d = *accum_ptr / SCROLL_UNITS_PER_TICK_D;
    assert(isfinite(scroll_ticks_d));
    /*
     * We intentionally use SCROLL_UNITS_PER_TICK here, not
     * SCROLL_UNITS_PER_TICK_D. The extra fraction of a scroll tick we would
     * gain from using SCROLL_UNITS_PER_TICK_D is not worthwhile, and having
     * the enforced threshold slightly lower than the real threshold is
     * arguably safer.
     */
    assert(scroll_ticks_d <= (INT32_MAX / SCROLL_UNITS_PER_TICK));
    assert(scroll_ticks_d >= (INT32_MIN / SCROLL_UNITS_PER_TICK));
    scroll_ticks = (int32_t)(scroll_ticks_d);
    if (scroll_ticks != 0) {
      (*accum_ptr) += -(scroll_ticks * SCROLL_UNITS_PER_TICK);
    }
  }

  return scroll_ticks;
}

