static void display_sync_maybe(void) {
  bool should_sync_displays = true;
  ssize_t i = 0;

  for (i = 0; i < MAX_SCREEN_COUNT; i++) {
    if (state.output_config_flag_list[i]) {
      /* Displays are mid-reconfiguration, skip sync for now */
      should_sync_displays = false;
      break;
    }
  }

  if (!should_sync_displays) {
    return;
  }

  for (i = 0; i < MAX_SCREEN_COUNT; i++) {
    if (state.wl_output_remove_flags[i]) {
      if (should_draw_cursor) {
        struct drawable_layer *layer = state.layers[i];
        zwlr_layer_surface_v1_destroy(layer->layer_surface);
        wl_surface_destroy(layer->surface);
        if (layer->layer_surface_configured) {
          assert(layer->size > 0);
          if (munmap(layer->pixbuf,
            (size_t)(layer->size) * MAX_UNRELEASED_FRAMES) == -1) {
            assert(false);
          }
          wl_shm_pool_destroy(layer->shm_pool);
        }
        free(layer);
        state.layers[i] = NULL;
      }

      wl_output_release(state.outputs[i]);
      state.outputs[i] = NULL;
      state.output_names[i] = 0;
      zxdg_output_v1_destroy(state.xdg_outputs[i]);
      state.xdg_outputs[i] = NULL;
      free(state.pending_output_geometries[i]);
      state.pending_output_geometries[i] = NULL;
      free(state.output_geometries[i]);
      state.output_geometries[i] = NULL;
      state.wl_output_remove_flags[i] = false;
    } else {
      struct output_geometry *geometry
        = state.pending_output_geometries[i];
      if (geometry == NULL) {
        continue;
      }
      if (state.output_geometries[i] == NULL) {
        state.output_geometries[i] = safe_calloc(1,
          sizeof(struct output_geometry));
      }
      memcpy(state.output_geometries[i], geometry,
        sizeof(struct output_geometry));
    }
  }

  if (!recalc_global_space()) {
    errx(1, "FATAL ERROR: Multiple screens are attached and gaps are present between them. kloak cannot operate in this configuration.");
  }
}

static bool recalc_global_space(void) {
  int32_t ul_corner_x = INT32_MAX;
  int32_t ul_corner_y = INT32_MAX;
  int32_t br_corner_x = INT32_MIN;
  int32_t br_corner_y = INT32_MIN;
  int32_t cur_geom_x = 0;
  int32_t cur_geom_y = 0;
  int32_t cur_geom_width = 0;
  int32_t cur_geom_height = 0;
  int32_t temp_br_x = 0;
  int32_t temp_br_y = 0;
  struct output_geometry *screen_list[MAX_SCREEN_COUNT];
  ssize_t screen_list_len = 0;
  struct output_geometry *conn_screen_list[MAX_SCREEN_COUNT];
  ssize_t conn_screen_list_len = 0;
  bool screen_in_conn_list = false;

  for (ssize_t i = 0; i < MAX_SCREEN_COUNT; i++) {
    if (!state.output_geometries[i]) {
      continue;
    }
    cur_geom_x = state.output_geometries[i]->x;
    cur_geom_y = state.output_geometries[i]->y;
    cur_geom_width = state.output_geometries[i]->width;
    cur_geom_height = state.output_geometries[i]->height;
    if (cur_geom_width <= 0 || cur_geom_height <= 0) {
      /*
       * labwc will send two wl_output::done events for each display, once
       * before we get position/size information from the XDG output protocol,
       * and once after. We should ignore displays that don't yet have
       * position/size information.
       */
      continue;
    }
    screen_list[screen_list_len] = state.output_geometries[i];
    screen_list_len++;
    if (cur_geom_x < ul_corner_x) {
      ul_corner_x = cur_geom_x;
    }
    if (cur_geom_y < ul_corner_y) {
      ul_corner_y = cur_geom_y;
    }
    temp_br_x = cur_geom_x + cur_geom_width;
    temp_br_y = cur_geom_y + cur_geom_height;
    if (temp_br_x > br_corner_x) {
      br_corner_x = temp_br_x;
    }
    if (temp_br_y > br_corner_y) {
      br_corner_y = temp_br_y;
    }
  }

  /* If we haven't gotten a valid state yet, report success and do nothing. */
  if (screen_list_len <= 0) {
    return true;
  }
  if (ul_corner_x > br_corner_x) {
    return true;
  }
  if (ul_corner_y > br_corner_y) {
    return true;
  }

  conn_screen_list[0] = screen_list[0];
  conn_screen_list_len = 1;

  /*
   * Check for gaps between the screens. We don't support running if gaps are
   * present. To do this, we start with an arbitrary screen, then find all
   * screens touching it, then find all screens touching those screens, and so
   * on, until we can't find any more screens touching whatever "zone" we
   * started in. If the number of connected screens is equal to the number of
   * attached screens, then all screens are connected, otherwise there is a
   * gap somewhere.
   */
  for (ssize_t i = 0; i < conn_screen_list_len; i++) {
    for (ssize_t j = 0; j < screen_list_len; j++) {
      screen_in_conn_list = false;
      for (ssize_t k = 0; k < conn_screen_list_len; k++) {
        if (screen_list[j] == conn_screen_list[k]) {
          screen_in_conn_list = true;
          break;
        }
      }
      if (screen_in_conn_list) {
        continue;
      }
      if (check_screen_touch(*(conn_screen_list[i]), *(screen_list[j]))) {
        /* Found a touching screen! */
        conn_screen_list[conn_screen_list_len] = screen_list[j];
        conn_screen_list_len++;
      }
    }
  }

  if (conn_screen_list_len != screen_list_len) {
    /* Debugging.
     *
     * warnx("DEBUG: Map of display geometries");
     * for (ssize_t z = 0; z < screen_list_len; z++) {
     *   warnx("DEBUG:   Screen %ld: x = %d, y = %d, width = %d, height = %d",
     *     z, screen_list[z]->x, screen_list[z]->y, screen_list[z]->width, screen_list[z]->height);
     * }
     */
    return false;
  }

  state.pointer_space_width = br_corner_x - ul_corner_x;
  state.pointer_space_height = br_corner_y - ul_corner_y;
  state.pointer_space_x = ul_corner_x;
  state.pointer_space_y = ul_corner_y;

  if (can_send_pointer_space_data) {
    send_pointer_space_data();
  }

  return true;
}

static struct drawable_layer *allocate_drawable_layer(
  struct wl_output *output) {
  struct drawable_layer *layer = safe_calloc(1, sizeof(struct drawable_layer));
  ssize_t i = 0;

  assert(should_draw_cursor);

  layer->last_drawn_cursor_x = -1;
  layer->last_drawn_cursor_y = -1;
  for (i = 0; i < MAX_UNRELEASED_FRAMES; i++) {
    layer->cursor_x_pos_list[i] = -1;
    layer->cursor_y_pos_list[i] = -1;
  }

  layer->frame_pending = true;
  layer->surface = wl_compositor_create_surface(state.compositor);
  if (!layer->surface) {
    err(1, "FATAL ERROR: Could not create wl_surface");
  }
  layer->layer_surface = zwlr_layer_shell_v1_get_layer_surface(
    state.layer_shell, layer->surface, output,
    ZWLR_LAYER_SHELL_V1_LAYER_OVERLAY, "com.kicksecure.kloak");
  if (!layer->layer_surface) {
    err(1, "FATAL ERROR: Could not create zwlr_layer_surface_v1");
  }
  if (zwlr_layer_surface_v1_add_listener(layer->layer_surface,
    &layer_surface_listener, NULL) == -1) {
    assert(false);
  }

  zwlr_layer_surface_v1_set_anchor(
    layer->layer_surface,
    ZWLR_LAYER_SURFACE_V1_ANCHOR_TOP |
    ZWLR_LAYER_SURFACE_V1_ANCHOR_BOTTOM |
    ZWLR_LAYER_SURFACE_V1_ANCHOR_LEFT |
    ZWLR_LAYER_SURFACE_V1_ANCHOR_RIGHT
  );
  zwlr_layer_surface_v1_set_exclusive_zone(layer->layer_surface, -1);
  wl_surface_commit(layer->surface);

  return layer;
}

static void damage_surface_enh(struct wl_surface *surface, int32_t x,
  int32_t y, int32_t width, int32_t height) {
  assert(should_draw_cursor);
  assert(width >= 0);
  assert(height >= 0);
  if (x < 0) x = 0;
  if (y < 0) y = 0;
  wl_surface_damage_buffer(surface, x, y, width, height);
}

static void draw_frame(struct drawable_layer *layer) {
  int32_t chosen_frame_idx = -1;
  int32_t frame_idx = 0;
  struct wl_buffer *buffer = NULL;
  struct screen_local_coord scr_coord = EMPTY_SCREEN_LOCAL_COORD;
  bool cursor_is_on_layer = false;
  ssize_t layer_idx = 0;

  assert(should_draw_cursor);
  assert(cursor_x <= INT32_MAX && cursor_x >= INT32_MIN);
  assert(cursor_y <= INT32_MAX && cursor_y >= INT32_MIN);

  if (!layer->layer_surface_configured) {
    return;
  }

  for (frame_idx = 0; frame_idx < MAX_UNRELEASED_FRAMES; frame_idx++) {
    if (!layer->frame_in_use[frame_idx]) {
      chosen_frame_idx = frame_idx;
      break;
    }
  }
  if (chosen_frame_idx == -1) {
    return;
  }

  assert(layer->size >= 0);
  assert(chosen_frame_idx >= 0);
  assert((layer->size * chosen_frame_idx)
    < (layer->size * MAX_UNRELEASED_FRAMES));

  layer->frame_pending = false;

  scr_coord = abs_coord_to_screen_local_coord((int32_t)(cursor_x),
    (int32_t)(cursor_y));
  cursor_is_on_layer = false;
  if (scr_coord.output_idx >= 0) {
    for (layer_idx = 0; layer_idx < MAX_SCREEN_COUNT; layer_idx++) {
      if ((state.layers[layer_idx] == layer)
        && (layer_idx == scr_coord.output_idx)) {
        cursor_is_on_layer = true;
      }
    }
  }

  /*
   * Unless we run into an absurdly big (billions of pixels in one dimension)
   * display, this shouldn't crash kloak due to signed integer over/underflow.
   */
  if (layer->last_drawn_cursor_x >= 0 && layer->last_drawn_cursor_y >= 0) {
    /* Damage the previous cursor location */
    damage_surface_enh(layer->surface,
      layer->last_drawn_cursor_x - CURSOR_RADIUS,
      layer->last_drawn_cursor_y - CURSOR_RADIUS,
      2 * CURSOR_RADIUS + 1,
      2 * CURSOR_RADIUS + 1);
  }
  if (cursor_is_on_layer) {
    /* Draw crosshairs at the pointer location */
    draw_block(layer->pixbuf,
      (layer->size * chosen_frame_idx) / (int32_t)(sizeof(uint32_t)),
      scr_coord.x, scr_coord.y, layer->width, layer->height, CURSOR_RADIUS,
      true);
    damage_surface_enh(layer->surface, scr_coord.x - CURSOR_RADIUS,
      scr_coord.y - CURSOR_RADIUS, 2 * CURSOR_RADIUS + 1,
      2 * CURSOR_RADIUS + 1);
  }

  /*
   * Technically we might end up drawing a frame when we drew and damaged
   * nothing, but this will likely only occur when a new display is plugged in,
   * so we'll likely lose more performance checking for this case than if we
   * simply allow it to happen.
   */

  buffer = wl_shm_pool_create_buffer(layer->shm_pool,
    layer->size * chosen_frame_idx, layer->width, layer->height,
    layer->stride, WL_SHM_FORMAT_ARGB8888);
  if (!buffer) {
    err(1, "FATAL ERROR: Could not create wl_buffer");
  }
  if (wl_buffer_add_listener(buffer, &buffer_listener, NULL) == -1) {
    assert(false);
  }
  layer->buffer_list[chosen_frame_idx] = buffer;
  wl_surface_attach(layer->surface, buffer, 0, 0);
  wl_surface_commit(layer->surface);

  if (cursor_is_on_layer) {
    layer->last_drawn_cursor_x = scr_coord.x;
    layer->last_drawn_cursor_y = scr_coord.y;
  } else {
    layer->last_drawn_cursor_x = -1;
    layer->last_drawn_cursor_y = -1;
  }
  layer->cursor_x_pos_list[chosen_frame_idx] = layer->last_drawn_cursor_x;
  layer->cursor_y_pos_list[chosen_frame_idx] = layer->last_drawn_cursor_y;
  layer->frame_in_use[chosen_frame_idx] = true;
}

static inline void wl_display_flush_safe(struct wl_display *display) {
  if (wl_display_flush(display) == -1) {
    if (errno == EAGAIN) {
      ev_fds[1].events |= POLLOUT;
    } else {
      err(1, "FATAL ERROR: Could not send data to Wayland server");
    }
  } else {
    ev_fds[1].events &= ~POLLOUT;
  }
}

static inline void wl_display_dispatch_pending_safe(
  struct wl_display *display) {
  if (wl_display_dispatch_pending(display) == -1) {
    errx(1, "FATAL ERROR: Could not dispatch Wayland events");
  }
}

static inline void wl_display_roundtrip_safe(struct wl_display *display) {
  if (wl_display_roundtrip(display) == -1) {
    errx(1, "FATAL ERROR: Could not roundtrip Wayland display");
  }
}

static int calc_poll_timeout(void) {
  const struct input_packet *packet = NULL;
  int64_t timeout_duration = 0;

  if (parse_ring_data_len > 0) {
    return 0;
  }

  packet = TAILQ_FIRST(&evq_head);
  if (packet == NULL) {
    return -1;
  }

  timeout_duration = packet->sched_time - current_time_ms();
  if (timeout_duration < 0) {
    return 0;
  }
  if (timeout_duration > INT_MAX) {
    return INT_MAX;
  }
  return (int)(timeout_duration);
}

static void make_virtual_cursor_pos_sane(double prev_cursor_x_pos,
  double prev_cursor_y_pos, double *cursor_x_ptr, double *cursor_y_ptr) {
  /*
   * We can't just look at the intended final location of the cursor and move
   * it there if that location is valid, since that would allow jumping over
   * "voids" in the compositor global space (places where global space has a
   * pixel but no screen covers that pixel). Instead, we use the following
   * algorithm:
   *
   * - Take the previous cursor position and treat it as a "start location".
   *   Treat the current cursor position as an "end location".
   * - Start walking in a straight line from the start location to the end
   *   location, one pixel at a time.
   * - Once we hit the end location, move the real mouse cursor there.
   * - Each time we walk forward a pixel, calculate the screen-local
   *   coordinates of that pixel, and ensure it actually is on a screen.
   * - If a pixel is NOT on any screen, determine which direction we can move
   *   to get back onto a screen. Move one pixel in that direction, then
   *   change the start location to this new position and adjust the end
   *   location so that we can walk to it moving in a straight line without
   *   moving any further in the dimension we just moved to get back to a
   *   screen. I.e., if we moved horizontally to the left one pixel to get
   *   back on a screen, move the end location so that we can walk to it in a
   *   vertical line. This allows us to "glide" along the wall.
   *
   * There may be a more efficient algorithm for this. Contributions welcome.
   */
  struct coord start = { 0 };
  struct coord end = { 0 };
  struct coord prev_trav_coord = { 0 };
  struct coord trav_coord = { 0 };
  struct screen_local_coord trav_scr_coord = EMPTY_SCREEN_LOCAL_COORD;

  if (!isfinite(*cursor_x_ptr) || !isfinite(*cursor_y_ptr)) {
    *cursor_x_ptr = prev_cursor_x_pos;
    *cursor_y_ptr = prev_cursor_y_pos;
    return;
  }
  if (*cursor_x_ptr < INT32_MIN) {
    *cursor_x_ptr = INT32_MIN;
  }
  if (*cursor_x_ptr > INT32_MAX) {
    *cursor_x_ptr = INT32_MAX;
  }
  if (*cursor_y_ptr < INT32_MIN) {
    *cursor_y_ptr = INT32_MIN;
  }
  if (*cursor_y_ptr > INT32_MAX) {
    *cursor_y_ptr = INT32_MAX;
  }
  start.x = (int32_t)(prev_cursor_x_pos);
  start.y = (int32_t)(prev_cursor_y_pos);
  end.x = (int32_t)(*cursor_x_ptr);
  end.y = (int32_t)(*cursor_y_ptr);
  prev_trav_coord = start;
  for (int32_t i = 1; ; i++) {
    bool traverse_line_success = false;
    trav_coord = traverse_line(start, end, i, &traverse_line_success);
    if (!traverse_line_success) {
      end.x = prev_trav_coord.x;
      end.y = prev_trav_coord.y;
      break;
    }
    trav_scr_coord = abs_coord_to_screen_local_coord(trav_coord.x,
      trav_coord.y);
    if (trav_scr_coord.output_idx < 0) {
      /*
       * Figure out what direction we moved when we went off screen, and move
       * move backwards in that direction, but in only one dimension.
       */
      if (prev_trav_coord.x < trav_coord.x) {
        trav_scr_coord = abs_coord_to_screen_local_coord(trav_coord.x - 1,
          trav_coord.y);
        if (trav_scr_coord.output_idx >= 0) {
          start.x = trav_coord.x - 1;
          start.y = trav_coord.y;
          end.x = trav_coord.x - 1;
          i = 0;
          continue;
        }
      }
      if (prev_trav_coord.x > trav_coord.x) {
        trav_scr_coord = abs_coord_to_screen_local_coord(trav_coord.x + 1,
          trav_coord.y);
        if (trav_scr_coord.output_idx >= 0) {
          start.x = trav_coord.x + 1;
          start.y = trav_coord.y;
          end.x = trav_coord.x + 1;
          i = 0;
          continue;
        }
      }
      if (prev_trav_coord.y < trav_coord.y) {
        trav_scr_coord = abs_coord_to_screen_local_coord(trav_coord.x,
          trav_coord.y - 1);
        if (trav_scr_coord.output_idx >= 0) {
          start.y = trav_coord.y - 1;
          start.x = trav_coord.x;
          end.y = trav_coord.y - 1;
          i = 0;
          continue;
        }
      }
      if (prev_trav_coord.y > trav_coord.y) {
        trav_scr_coord = abs_coord_to_screen_local_coord(trav_coord.x,
          trav_coord.y + 1);
        if (trav_scr_coord.output_idx >= 0) {
          start.y = trav_coord.y + 1;
          start.x = trav_coord.x;
          end.y = trav_coord.y + 1;
          i = 0;
          continue;
        }
      }
      /*
       * If all of the above fail, we've gone diagonally off a screen and into
       * compositor global space. Move the cursor back to where it was and
       * stop it. Technically we should also be doing this if two different
       * directions both work to get us back on-screen, but we don't currently
       * and the one-pixel shift resulting from this likely isn't worth caring
       * about.
       *
       * TODO: Is there a reason to care about this one-pixel shift? Does its
       * existence leak information an attacker wouldn't be able to get
       * otherwise?
       */
      end.x = prev_trav_coord.x;
      end.y = prev_trav_coord.y;
      break;
    }
    prev_trav_coord = trav_coord;
  }
  *(cursor_x_ptr) = end.x;
  *(cursor_y_ptr) = end.y;
}

static struct input_packet *find_merge_target_packet(
  enum input_packet_type target_packet_type,
  const enum input_packet_type *ignore_packet_type_list) {
  struct input_packet *found_packet = NULL;

  /*
   * TAILQ_FOREACH_REVERSE would be useful here, but it is not documented to be
   * implemented using a loop, therefore it may be unsafe to use break
   * statements within it. We implement a loop manually for this reason.
   */

  found_packet = TAILQ_LAST(&evq_head, tailhead_evq);

  while (found_packet != NULL) {
    bool do_ignore_packet = false;

    if (found_packet->packet_type == target_packet_type) {
      break;
    }

    for (ssize_t i = 0; ; i++) {
      enum input_packet_type ignore_packet_type = ignore_packet_type_list[i];
      if (ignore_packet_type == 0) {
        break;
      }
      if (found_packet->packet_type == ignore_packet_type) {
        do_ignore_packet = true;
        break;
      }
    }

    if (!do_ignore_packet) {
      found_packet = NULL;
      break;
    }

    found_packet = TAILQ_PREV(found_packet, tailhead_evq, evq_entries);
  }

  return found_packet;
}

static struct input_packet *update_virtual_cursor(void) {
  struct screen_local_coord prev_scr_coord = EMPTY_SCREEN_LOCAL_COORD;
  struct screen_local_coord scr_coord = EMPTY_SCREEN_LOCAL_COORD;
  struct input_packet *old_ev_packet = NULL;
  struct input_packet *ev_packet = NULL;

  assert(prev_cursor_x <= INT32_MAX && prev_cursor_x >= INT32_MIN);
  assert(prev_cursor_y <= INT32_MAX && prev_cursor_y >= INT32_MIN);

  prev_scr_coord = abs_coord_to_screen_local_coord((int32_t)(prev_cursor_x),
    (int32_t)(prev_cursor_y));

  if (prev_scr_coord.output_idx < 0) {
    /*
     * Previous cursor position is no longer valid. This can happen during
     * early startup or when a screen is removed. Relocate the cursor to the
     * upper left corner of an arbitrary screen.
     */
    for (int32_t i = 0; i < MAX_SCREEN_COUNT; i++) {
      if (state.output_geometries[i]) {
        bool sane_location_valid = false;
        struct coord sane_location = screen_local_coord_to_abs_coord(0, 0, i,
          &sane_location_valid);

        assert(sane_location_valid);
        assert(sane_location.x <= INT32_MAX && sane_location.x >= INT32_MIN);
        assert(sane_location.y <= INT32_MAX && sane_location.y >= INT32_MIN);
        prev_cursor_x = sane_location.x;
        prev_cursor_y = sane_location.y;
        cursor_x = sane_location.x;
        cursor_y = sane_location.y;
        prev_scr_coord = abs_coord_to_screen_local_coord(
          (int32_t)(prev_cursor_x), (int32_t)(prev_cursor_y));
        if (prev_scr_coord.output_idx >= 0) {
          break;
        }
        assert(false);
      }
    }
    if (prev_scr_coord.output_idx < 0) {
      /* No screens attached, bail out and don't create any new input_packet */
      return NULL;
    }
  }

  make_virtual_cursor_pos_sane(prev_cursor_x, prev_cursor_y, &cursor_x,
    &cursor_y);

  assert(isfinite(cursor_x) && cursor_x <= INT32_MAX && cursor_x >= INT32_MIN);
  assert(isfinite(cursor_y) && cursor_y <= INT32_MAX && cursor_y >= INT32_MIN);
  /*
   * Exact equality testing is intentional, prev_cursor_* is set from cursor_*
   * and we are testing for that specific case. There is no risk of rounding
   * errors causing minor differences.
   */
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wfloat-equal"
  if (cursor_x == prev_cursor_x && cursor_y == prev_cursor_y) {
#pragma GCC diagnostic pop
    return NULL;
  }

  scr_coord = abs_coord_to_screen_local_coord((int32_t)(cursor_x),
    (int32_t)(cursor_y));

  assert(prev_scr_coord.output_idx >= 0);
  assert(scr_coord.output_idx >= 0);
  if (should_draw_cursor) {
    state.layers[prev_scr_coord.output_idx]->frame_pending = true;
    state.layers[scr_coord.output_idx]->frame_pending = true;
  }

  old_ev_packet = find_merge_target_packet(
    KLOAK_PACKET_TYPE_MOUSEMOVE,
    (const enum input_packet_type[]){KLOAK_PACKET_TYPE_MOUSESCROLL, 0}
  );
  if (old_ev_packet != NULL) {
    old_ev_packet->data.coord_data.x = (int32_t)(cursor_x);
    old_ev_packet->data.coord_data.y = (int32_t)(cursor_y);
    return NULL;
  } else {
    ev_packet = safe_calloc(1, sizeof(struct input_packet));
    ev_packet->packet_type = KLOAK_PACKET_TYPE_MOUSEMOVE;
    ev_packet->data.coord_data.x = (int32_t)(cursor_x);
    ev_packet->data.coord_data.y = (int32_t)(cursor_y);
    return ev_packet;
  }
}

static struct input_packet *update_mouse_scroll(void) {
  int32_t vert_scroll_ticks = get_ticks_from_scroll_accum(&vert_scroll_accum);
  int32_t horiz_scroll_ticks
    = get_ticks_from_scroll_accum(&horiz_scroll_accum);
  struct input_packet *old_ev_packet = NULL;
  struct input_packet *ev_packet = NULL;

  if ((vert_scroll_ticks != 0) || (horiz_scroll_ticks != 0)) {
    old_ev_packet = find_merge_target_packet(
      KLOAK_PACKET_TYPE_MOUSESCROLL,
      (const enum input_packet_type[]){KLOAK_PACKET_TYPE_MOUSEMOVE, 0}
    );
    if (old_ev_packet != NULL) {
      old_ev_packet->data.coord_data.y += vert_scroll_ticks;
      old_ev_packet->data.coord_data.x += horiz_scroll_ticks;
      return NULL;
    } else {
      ev_packet = safe_calloc(1, sizeof(struct input_packet));
      ev_packet->packet_type = KLOAK_PACKET_TYPE_MOUSESCROLL;
      ev_packet->data.coord_data.y = vert_scroll_ticks;
      ev_packet->data.coord_data.x = horiz_scroll_ticks;
      return ev_packet;
    }
  }

  return NULL;
}

static bool process_parent_message(void) {
  enum ptc_packet_type msg_type = 0;
  void *msg_obj = NULL;
  struct double_coord *double_coord_ptr = NULL;
  struct button_event *button_event_ptr = NULL;
  struct input_packet *ev_packet = NULL;
  int64_t current_time = 0;
  int64_t lower_bound = 0;
  int64_t random_delay = 0;
  msg_obj = get_msg_from_peer(&msg_type, NULL);

  if (msg_type == 0) {
    return false;
  }

  switch (msg_type) {
  case PTC_PACKET_CURSOR_REL_EVENT:
    double_coord_ptr = (struct double_coord *)(msg_obj);
    assert(isfinite(double_coord_ptr->x));
    assert(isfinite(double_coord_ptr->y));
    prev_cursor_x = cursor_x;
    prev_cursor_y = cursor_y;
    cursor_x += double_coord_ptr->x;
    cursor_y += double_coord_ptr->y;
    free(msg_obj);
    assert(isfinite(cursor_x));
    assert(isfinite(cursor_y));
    ev_packet = update_virtual_cursor();
    if (ev_packet == NULL) {
      return true;
    }
    break;

  case PTC_PACKET_CURSOR_ABS_EVENT:
    double_coord_ptr = (struct double_coord *)(msg_obj);
    assert(isfinite(double_coord_ptr->x));
    assert(isfinite(double_coord_ptr->y));
    prev_cursor_x = cursor_x;
    prev_cursor_y = cursor_y;
    cursor_x = double_coord_ptr->x + state.pointer_space_x;
    cursor_y = double_coord_ptr->y + state.pointer_space_y;
    free(msg_obj);
    assert(isfinite(cursor_x));
    assert(isfinite(cursor_y));
    ev_packet = update_virtual_cursor();
    if (ev_packet == NULL) {
      return true;
    }
    break;

  case PTC_PACKET_SCROLL_EVENT:
    double_coord_ptr = (struct double_coord *)(msg_obj);
    assert(isfinite(double_coord_ptr->x));
    assert(isfinite(double_coord_ptr->y));
    vert_scroll_accum += double_coord_ptr->y;
    horiz_scroll_accum += double_coord_ptr->x;
    free(msg_obj);
    assert(isfinite(vert_scroll_accum));
    assert(isfinite(horiz_scroll_accum));
    ev_packet = update_mouse_scroll();
    if (ev_packet == NULL) {
      return true;
    }
    break;

  case PTC_PACKET_CLICK_EVENT:
    button_event_ptr = (struct button_event *)(msg_obj);
    ev_packet = safe_calloc(1, sizeof(struct input_packet));
    ev_packet->packet_type = KLOAK_PACKET_TYPE_CLICK;
    memcpy(&ev_packet->data.button_data, button_event_ptr,
      sizeof(struct button_event));
    free(msg_obj);
    break;

  case PTC_PACKET_KB_EVENT:
    button_event_ptr = (struct button_event *)(msg_obj);
    ev_packet = safe_calloc(1, sizeof(struct input_packet));
    ev_packet->packet_type = KLOAK_PACKET_TYPE_KB;
    memcpy(&ev_packet->data.button_data, button_event_ptr,
      sizeof(struct button_event));
    free(msg_obj);
    break;

  default:
    errx(1, "FATAL ERROR: Unexpected message type %u from parent", msg_type);
  }

  current_time = current_time_ms();
  lower_bound = MIN(MAX(prev_release_time - current_time, 0), max_delay);
  random_delay = random_between(lower_bound, max_delay);
  ev_packet->sched_time = current_time + random_delay;
  TAILQ_INSERT_TAIL(&evq_head, ev_packet, evq_entries);
  prev_release_time = ev_packet->sched_time;
  return true;
}

static void release_scheduled_input_events(void) {
  int64_t current_time = current_time_ms();
  struct input_packet *ev_packet = NULL;
  int32_t pointer_x = 0;
  int32_t pointer_y = 0;
  bool send_axis_source_and_frame = false;
  uint32_t button_code = 0;
  bool is_pressed = false;
  xkb_mod_mask_t depressed_mods;
  xkb_mod_mask_t latched_mods;
  xkb_mod_mask_t locked_mods;
  xkb_layout_index_t effective_group;

  while ((ev_packet = TAILQ_FIRST(&evq_head))
    && (current_time >= ev_packet->sched_time)) {
    assert(ev_packet->sched_time >= 0);

    /*
     * ev_packet->sched_time wraparound during cast to uint32_t is
     * intentional.
     */

    switch (ev_packet->packet_type) {
    case KLOAK_PACKET_TYPE_MOUSEMOVE:
      /*
       * zwlr_virtual_pointer_v1_motion_absolute wants coordinates in pointer
       * space. while ev_packet stores them in compositor global space. We
       * cannot convert to pointer space until this moment since a display may
       * have been removed between when the event was scheduled and when it was
       * released.
       */
      pointer_x = ev_packet->data.coord_data.x - state.pointer_space_x;
      pointer_y = ev_packet->data.coord_data.y - state.pointer_space_y;
      if (pointer_x < 0 || pointer_y < 0
        || pointer_x >= state.pointer_space_width
        || pointer_y >= state.pointer_space_height) {
        /* Mouse event is not valid, probably due to display state change. */
        break;
      }
      zwlr_virtual_pointer_v1_motion_absolute(
        state.virt_pointer, (uint32_t)(ev_packet->sched_time),
        (uint32_t)(pointer_x), (uint32_t)(pointer_y),
        (uint32_t)(state.pointer_space_width),
        (uint32_t)(state.pointer_space_height));
      zwlr_virtual_pointer_v1_frame(state.virt_pointer);
      break;

    case KLOAK_PACKET_TYPE_MOUSESCROLL:
      send_axis_source_and_frame = false;
      if (ev_packet->data.coord_data.y != 0) {
        zwlr_virtual_pointer_v1_axis(state.virt_pointer,
          (uint32_t)(ev_packet->sched_time), WL_POINTER_AXIS_VERTICAL_SCROLL,
          wl_fixed_from_int(ev_packet->data.coord_data.y
            * SCROLL_ANGLE_PER_TICK));
        /*
         * wlroots (or labwc?) apparently wants a double-negative for scrolling
         * up or left. If 'value' is always positive and 'discrete' is allowed
         * to be negative, most apps behave properly but Meld will only scroll
         * down and right. If 'value' is allowed to be negative and 'discrete'
         * is always positive, Qt apps will only scroll down. When both are
         * allowed to be negative, scrolling works correctly.
         */
        zwlr_virtual_pointer_v1_axis_discrete(state.virt_pointer,
          (uint32_t)(ev_packet->sched_time), WL_POINTER_AXIS_VERTICAL_SCROLL,
          ev_packet->data.coord_data.y >= 0
            ? wl_fixed_from_int(SCROLL_ANGLE_PER_TICK)
            : wl_fixed_from_int(-SCROLL_ANGLE_PER_TICK),
          ev_packet->data.coord_data.y);
        send_axis_source_and_frame = true;
      }
      if (ev_packet->data.coord_data.x != 0) {
        zwlr_virtual_pointer_v1_axis(state.virt_pointer,
          (uint32_t)(ev_packet->sched_time), WL_POINTER_AXIS_HORIZONTAL_SCROLL,
          wl_fixed_from_int(ev_packet->data.coord_data.x
            * SCROLL_ANGLE_PER_TICK));
        zwlr_virtual_pointer_v1_axis_discrete(state.virt_pointer,
          (uint32_t)(ev_packet->sched_time), WL_POINTER_AXIS_HORIZONTAL_SCROLL,
          ev_packet->data.coord_data.x >= 0
            ? wl_fixed_from_int(SCROLL_ANGLE_PER_TICK)
            : wl_fixed_from_int(-SCROLL_ANGLE_PER_TICK),
          ev_packet->data.coord_data.x);
        send_axis_source_and_frame = true;
      }
      if (send_axis_source_and_frame) {
        zwlr_virtual_pointer_v1_axis_source(state.virt_pointer,
          WL_POINTER_AXIS_SOURCE_WHEEL);
        zwlr_virtual_pointer_v1_frame(state.virt_pointer);
      }
      break;

    case KLOAK_PACKET_TYPE_CLICK:
      zwlr_virtual_pointer_v1_button(state.virt_pointer,
        (uint32_t)(ev_packet->sched_time),
        ev_packet->data.button_data.button_code,
        ev_packet->data.button_data.is_pressed
          ? WL_POINTER_BUTTON_STATE_PRESSED
          : WL_POINTER_BUTTON_STATE_RELEASED);
      zwlr_virtual_pointer_v1_frame(state.virt_pointer);
      break;

    case KLOAK_PACKET_TYPE_KB:
      button_code = ev_packet->data.button_data.button_code;
      is_pressed = ev_packet->data.button_data.is_pressed;
      /*
       * XKB keycodes == evdev keycodes + 8. Why this design decision was
       * made, I have no idea.
       */
      xkb_state_update_key(state.xkb_state, button_code + 8,
        is_pressed ? XKB_KEY_DOWN : XKB_KEY_UP);
      depressed_mods = xkb_state_serialize_mods(
        state.xkb_state, XKB_STATE_MODS_DEPRESSED);
      latched_mods = xkb_state_serialize_mods(
        state.xkb_state, XKB_STATE_MODS_LATCHED);
      locked_mods = xkb_state_serialize_mods(
        state.xkb_state, XKB_STATE_MODS_LOCKED);
      effective_group = xkb_state_serialize_layout(
        state.xkb_state, XKB_STATE_LAYOUT_EFFECTIVE);
      if (depressed_mods != last_depressed_mods
        || latched_mods != last_latched_mods
        || locked_mods != last_locked_mods
        || effective_group != last_effective_group) {
        zwp_virtual_keyboard_v1_modifiers(state.virt_kb, depressed_mods,
          latched_mods, locked_mods, effective_group);
        last_depressed_mods = depressed_mods;
        last_latched_mods = latched_mods;
        last_locked_mods = locked_mods;
        last_effective_group = effective_group;
      }
      zwp_virtual_keyboard_v1_key(state.virt_kb,
        (uint32_t)(ev_packet->sched_time), button_code, is_pressed
          ? WL_KEYBOARD_KEY_STATE_PRESSED : WL_KEYBOARD_KEY_STATE_RELEASED);
      break;

    default:
      assert(false);
      break;
    }
    TAILQ_REMOVE(&evq_head, ev_packet, evq_entries);
    free(ev_packet);
  }
}

