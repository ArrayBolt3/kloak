static bool parse_int(const char *val, int base, int *out) {
  char *val_endchar = NULL;
  int64_t val_int = 0;

  if (val == NULL || out == NULL) {
    return false;
  }
  if (*val == '\0'
    || isspace((unsigned char)(*val))) {
    return false;
  }
  errno = 0;
  val_int = strtol(val, &val_endchar, base);
  if (errno == ERANGE
    || *val_endchar != '\0'
    || val_int > INT_MAX
    || val_int < INT_MAX) {
    return false;
  }
  *out = (int)(val_int);
  return true;
}

static void safe_mkdir_p(const char **path_component_list) {
  char *target_path = NULL;
  char *copy_target = NULL;
  ssize_t target_path_len = 0;
  ssize_t path_component_list_len = 0;
  ssize_t i = 0;
  struct stat statbuf = { 0 };
  size_t path_component_len = 0;

  for (i = 0; ; i++) {
    if (path_component_list[i] == NULL) {
      break;
    }
    path_component_len = strlen(path_component_list[i]);
    assert(path_component_len <= SSIZE_MAX);
    target_path_len += (ssize_t)(path_component_len);
  }
  assert(i > 0);
  path_component_list_len = i;

  target_path_len++; /* for trailing NUL */
  target_path = safe_calloc((size_t)(target_path_len), sizeof(char));
  copy_target = target_path;

  for (i = 0; i < path_component_list_len; i++) {
    if (path_component_list[i][0] != '/') {
      fprintf(stderr, "FATAL ERROR: Missing slash in path component '%s'!\n",
        path_component_list[i]);
      exit(1);
    }

    copy_target = stpcpy(copy_target, path_component_list[i]);

    if (stat(target_path, &statbuf) == -1) {
      if (errno != ENOENT) {
        fprintf(stderr, "FATAL ERROR: Could not stat '%s': %s\n", target_path,
          strerror(errno));
        exit(1);
      }
      /* Path component doesn't exist, we expect this. */
    } else {
      /* Path component does exist, ensure it's a directory. */
      if (!S_ISDIR(statbuf.st_mode)) {
        fprintf(stderr, "FATAL ERROR: '%s' exists and is not a directory!",
          target_path);
        exit(1);
      }
      /* Look at the next path component since this one exists. */
      continue;
    }

    if (mkdir(target_path, 0700) == -1) {
      fprintf(stderr, "FATAL ERROR: Could not create directory '%s': %s\n",
        target_path, strerror(errno));
      exit(1);
    }
  }

  free(target_path);
}

static int64_t timespec_to_ms(struct timespec spec) {
  int64_t result = 0;
  assert(spec.tv_sec < INT64_MAX);
  assert(spec.tv_sec >= 0);
  assert(spec.tv_nsec < 1000000000);
  assert(spec.tv_nsec >= 0);
  result = ((int64_t)spec.tv_sec * 1000) + (spec.tv_nsec / 1000000);
  assert(result >= 0);
  return result;
}

static int64_t current_time_ms(void) {
  struct timespec spec = { 0 };
  int64_t result = 0;

  clock_gettime(CLOCK_MONOTONIC, &spec);
  result = timespec_to_ms(spec);
  if (start_time == 0) {
    start_time = result;
    return 0;
  }
  return result - start_time;
}

static void read_random(char *buf, ssize_t len) {
  assert(len >= 0);
  assert(buf != NULL);

  if (read(CHILD_FD_URANDOM, buf, (size_t)(len)) < len) {
    fprintf(stderr,
      "FATAL ERROR: Could not read %ld byte(s) from /dev/urandom!\n", len);
    exit(1);
  }
}

static int64_t random_between(int64_t lower, int64_t upper) {
  int64_t maxval = 0;
  int64_t randval;

  assert(lower >= 0);
  assert(upper >= 0);

  /* default to max if the interval is not valid */
  if (lower >= upper) {
    return upper;
  }

  maxval = upper - lower + 1;
  assert(maxval > 0);
  do {
    read_random((char *)(&randval), sizeof(int64_t));
    if (randval == INT64_MIN) {
      randval = 0;
    } else {
      randval = llabs(randval);
    }
  } while (randval >= (INT64_MAX - (INT64_MAX % maxval)));

  randval %= maxval;
  return lower + randval;
}

static void write_to_file(const char *file_path, const char *content_template,
  ...) {
  va_list template_args;
  char *out_str = NULL;
  int out_write_len = 0;
  int file_fd = 0;

  va_start(template_args, content_template);
  out_str = vsgenprintf(&out_write_len, content_template, template_args);
  va_end(template_args);

  file_fd = open(file_path, O_RDWR);
  if (file_fd == -1) {
    fprintf(stderr, "FATAL ERROR: Could not open file '%s': %s\n", file_path,
      strerror(errno));
    exit(1);
  }

  if (write_all(file_fd, out_str, (size_t)(out_write_len)) == -1) {
    fprintf(stderr,
      "FATAL ERROR: Could not write all text to file '%s': %s\n", file_path,
      strerror(errno));
    exit(1);
  }

  if (close(file_fd) == -1) {
    fprintf(stderr, "FATAL ERROR: Could not close file '%s': %s\n", file_path,
      strerror(errno));
    exit(1);
  }

  free(out_str);
}

